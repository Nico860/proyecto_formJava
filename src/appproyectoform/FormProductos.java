    private boolean existeCodigo(String codigo){
        for (int i = 0; i < DBRegistros.productos.size(); i++) {
            Producto e = DBRegistros.productos.get(i);

            if (e.getCodigo().equalsIgnoreCase(codigo)) {
                return true;
            }
        }

        return false;
    }
    
